-- =====================================================================
-- huaxi-data-agent 平台表 PG 建表脚本（M-H1 交付物）
-- 在华西业务库执行（同库同 schema=public）；幂等可重复执行。
-- 七张表全部在 data-agent 的 excludeTables 排除清单里（M-Schema 不扫）。
-- 注意：应用启动时也会自动幂等建表（各 Manager 内建 DDL），
--       本脚本是提前建表/DBA 审核用途，两者结构保持一致（UPSTREAM.md 冲突区）。
-- =====================================================================

-- 1. 会话窗口表
CREATE TABLE IF NOT EXISTS agentx_conversation (
  id bigint NOT NULL,
  conversation_id varchar(100) NOT NULL,
  session_id varchar(100) NOT NULL,
  user_id varchar(100) NULL,
  question text NOT NULL,
  status varchar(20) NULL DEFAULT 'running',
  created_at timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at timestamp NULL DEFAULT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_conv_session UNIQUE (session_id)
);
CREATE INDEX IF NOT EXISTS idx_conv_id ON agentx_conversation (conversation_id);

-- 2. 会话消息链表
CREATE TABLE IF NOT EXISTS agentx_session (
  id bigint NOT NULL,
  conversation_id varchar(100) NOT NULL,
  session_id varchar(100) NOT NULL,
  state_key varchar(255) NOT NULL,
  item_index int NOT NULL DEFAULT 0,
  state_data text NOT NULL,
  created_at timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_session_state ON agentx_session (session_id, state_key);
CREATE INDEX IF NOT EXISTS idx_conv_state ON agentx_session (conversation_id, state_key);

-- 3. 追踪审计表
CREATE TABLE IF NOT EXISTS agentx_trace (
  id bigint NOT NULL,
  session_id varchar(100) NOT NULL,
  conversation_id varchar(100) NOT NULL,
  round int NOT NULL,
  input_data text NULL,
  output_data text NULL,
  think text NULL,
  prompt_tokens bigint NULL DEFAULT 0,
  completion_tokens bigint NULL DEFAULT 0,
  duration_ms bigint NULL DEFAULT 0,
  success int NULL DEFAULT 1,
  error_message text NULL,
  created_at timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_agentx_trace_session ON agentx_trace (session_id);
CREATE INDEX IF NOT EXISTS idx_agentx_trace_conv ON agentx_trace (conversation_id);

-- 4. 暂停现场快照表
CREATE TABLE IF NOT EXISTS agentx_pause_state (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  conversation_id varchar(100) NOT NULL,
  reason varchar(50) NOT NULL,
  safe_point varchar(50) DEFAULT NULL,
  current_round int NOT NULL,
  interrupted_at timestamp NOT NULL,
  expires_at timestamp NULL DEFAULT NULL,
  snapshot_json text NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_conversation_id UNIQUE (conversation_id)
);
CREATE INDEX IF NOT EXISTS idx_pause_state_expires ON agentx_pause_state (expires_at);

-- 5. 技能表
CREATE TABLE IF NOT EXISTS agentx_skill (
  id bigint NOT NULL,
  name varchar(500) NOT NULL,
  skill_path varchar(3000) DEFAULT NULL,
  description varchar(3000) DEFAULT '',
  enabled smallint NOT NULL DEFAULT 1,
  file_name varchar(255) DEFAULT NULL,
  source varchar(20) DEFAULT NULL,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_agentx_skill_name ON agentx_skill (name);

-- 6. MCP 服务表
CREATE TABLE IF NOT EXISTS agentx_mcp_server (
  id bigint NOT NULL,
  name varchar(64) NOT NULL,
  transport varchar(20) NOT NULL DEFAULT 'STREAMABLE',
  url varchar(500) DEFAULT NULL,
  sse_endpoint varchar(200) DEFAULT NULL,
  command varchar(200) DEFAULT NULL,
  args varchar(2000) DEFAULT NULL,
  env varchar(2000) DEFAULT NULL,
  auth_type varchar(20) NOT NULL DEFAULT 'NONE',
  auth_token varchar(1000) DEFAULT NULL,
  timeout_ms int NOT NULL DEFAULT 60000,
  inject_mode varchar(20) NOT NULL DEFAULT 'ALWAYS',
  enabled smallint NOT NULL DEFAULT 1,
  source varchar(20) DEFAULT NULL,
  status varchar(20) NOT NULL DEFAULT 'UNKNOWN',
  last_error varchar(2000) DEFAULT NULL,
  tool_count int DEFAULT NULL,
  last_check_time timestamp DEFAULT NULL,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_agentx_mcp_server_name ON agentx_mcp_server (name);

-- 7. 文件表
CREATE TABLE IF NOT EXISTS agentx_file (
  id bigint NOT NULL,
  file_id varchar(64) NOT NULL,
  file_name varchar(255) NOT NULL,
  file_type varchar(32),
  file_size bigint,
  minio_path varchar(512),
  extracted_text text,
  status varchar(16) NOT NULL,
  embed smallint NOT NULL DEFAULT 0,
  conversation_id varchar(64),
  session_id bigint,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_file_id UNIQUE (file_id)
);
CREATE INDEX IF NOT EXISTS idx_agentx_file_session ON agentx_file (session_id);
CREATE INDEX IF NOT EXISTS idx_agentx_file_conv ON agentx_file (conversation_id);

-- 8. 动作审计表（M-E0 写通道：写操作结构化审计，conversation_id 关联 agentx_trace 回放）
CREATE TABLE IF NOT EXISTS agentx_action_log (
  id bigint NOT NULL,
  conversation_id varchar(100) DEFAULT NULL,
  user_id bigint DEFAULT NULL,
  tool varchar(100) NOT NULL,
  action varchar(100) DEFAULT NULL,
  business_object varchar(500) DEFAULT NULL,
  confirm_token varchar(64) DEFAULT NULL,
  success smallint DEFAULT 1,
  error_message text,
  detail text,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_agentx_action_log_conv ON agentx_action_log (conversation_id);
CREATE INDEX IF NOT EXISTS idx_agentx_action_log_user ON agentx_action_log (user_id);

-- 9. HITL 决策单主表（一期：唯一真相，严禁物理删除）
CREATE TABLE IF NOT EXISTS agentx_decision (
  decision_id        varchar(64)  NOT NULL,
  conversation_id    varchar(100) NOT NULL,
  session_id         varchar(100) NOT NULL,
  tool_call_id       varchar(100) DEFAULT NULL,
  agent_code         varchar(64)  DEFAULT NULL,
  owner_user_id      bigint       NOT NULL,
  type               varchar(32)  NOT NULL,
  status             varchar(32)  NOT NULL,
  revision           int          NOT NULL DEFAULT 1,
  tool_name          varchar(100) NOT NULL,
  scope_key          varchar(255) DEFAULT NULL,
  action_summary     text         NOT NULL,
  payload_json       text         NOT NULL,
  payload_hash       varchar(128) NOT NULL,
  options_json       text         DEFAULT NULL,
  decision_option    varchar(64)  DEFAULT NULL,
  answer_json        text         DEFAULT NULL,
  user_words         text         DEFAULT NULL,
  grant_id           varchar(64)  DEFAULT NULL,
  answered_by        bigint       DEFAULT NULL,
  answered_by_name   varchar(100) DEFAULT NULL,
  client_ip          varchar(64)  DEFAULT NULL,
  command_id         varchar(64)  DEFAULT NULL,
  expires_at         timestamp    NOT NULL,
  created_at         timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  answered_at        timestamp    DEFAULT NULL,
  consumed_at        timestamp    DEFAULT NULL,
  PRIMARY KEY (decision_id)
);
CREATE INDEX IF NOT EXISTS idx_decision_conv_status ON agentx_decision (conversation_id, status);
CREATE INDEX IF NOT EXISTS idx_decision_owner_status ON agentx_decision (owner_user_id, status, expires_at);
CREATE UNIQUE INDEX IF NOT EXISTS uk_decision_cmd ON agentx_decision (decision_id, command_id) WHERE command_id IS NOT NULL;

-- 10. 会话级同类授权表（一期）
CREATE TABLE IF NOT EXISTS agentx_decision_grant (
  grant_id           varchar(64)  NOT NULL,
  user_id            bigint       NOT NULL,
  conversation_id    varchar(100) NOT NULL,
  source_decision_id varchar(64)  NOT NULL,
  tool_name          varchar(100) NOT NULL,
  scope_key          varchar(255) NOT NULL,
  scope_desc         varchar(500) DEFAULT NULL,
  status             varchar(20)  NOT NULL DEFAULT 'ACTIVE',
  max_uses           int          NOT NULL DEFAULT 20,
  used_count         int          NOT NULL DEFAULT 0,
  expires_at         timestamp    NOT NULL,
  created_at         timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  revoked_at         timestamp    DEFAULT NULL,
  PRIMARY KEY (grant_id)
);
CREATE INDEX IF NOT EXISTS idx_grant_lookup ON agentx_decision_grant (user_id, conversation_id, scope_key, status);

-- 11. 动作审计表扩展 decision_id 关联决策单
ALTER TABLE agentx_action_log ADD COLUMN IF NOT EXISTS decision_id varchar(64) DEFAULT NULL;
CREATE INDEX IF NOT EXISTS idx_action_log_decision ON agentx_action_log (decision_id);
