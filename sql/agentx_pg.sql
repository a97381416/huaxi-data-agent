-- =====================================================================
-- huaxi-data-agent 平台表 PG 建表脚本（M-H1 交付物）
-- 在华西业务库执行（同库同 schema=public）；幂等可重复执行。
-- 七张表全部在 data-agent 的 excludeTables 排除清单里（M-Schema 不扫）。
-- 注意：应用启动时也会自动幂等建表（各 Manager 内建 DDL），
--       本脚本是提前建表/DBA 审核用途，两者结构保持一致（UPSTREAM.md 冲突区）。
-- =====================================================================

-- 1. 会话窗口表
CREATE TABLE IF NOT EXISTS agentx_conversation (
  id bigint NOT NULL,
  conversation_id varchar(100) NOT NULL,
  session_id varchar(100) NOT NULL,
  user_id varchar(100) NULL,
  question text NOT NULL,
  status varchar(20) NULL DEFAULT 'running',
  created_at timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at timestamp NULL DEFAULT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_conv_session UNIQUE (session_id)
);
CREATE INDEX IF NOT EXISTS idx_conv_id ON agentx_conversation (conversation_id);

-- 2. 会话消息链表
CREATE TABLE IF NOT EXISTS agentx_session (
  id bigint NOT NULL,
  conversation_id varchar(100) NOT NULL,
  session_id varchar(100) NOT NULL,
  state_key varchar(255) NOT NULL,
  item_index int NOT NULL DEFAULT 0,
  state_data text NOT NULL,
  created_at timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_session_state ON agentx_session (session_id, state_key);
CREATE INDEX IF NOT EXISTS idx_conv_state ON agentx_session (conversation_id, state_key);

-- 3. 追踪审计表
CREATE TABLE IF NOT EXISTS agentx_trace (
  id bigint NOT NULL,
  session_id varchar(100) NOT NULL,
  conversation_id varchar(100) NOT NULL,
  round int NOT NULL,
  input_data text NULL,
  output_data text NULL,
  think text NULL,
  prompt_tokens bigint NULL DEFAULT 0,
  completion_tokens bigint NULL DEFAULT 0,
  duration_ms bigint NULL DEFAULT 0,
  success int NULL DEFAULT 1,
  error_message text NULL,
  created_at timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_agentx_trace_session ON agentx_trace (session_id);
CREATE INDEX IF NOT EXISTS idx_agentx_trace_conv ON agentx_trace (conversation_id);

-- 4. 暂停现场快照表
CREATE TABLE IF NOT EXISTS agentx_pause_state (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  conversation_id varchar(100) NOT NULL,
  reason varchar(50) NOT NULL,
  safe_point varchar(50) DEFAULT NULL,
  current_round int NOT NULL,
  interrupted_at timestamp NOT NULL,
  expires_at timestamp NULL DEFAULT NULL,
  snapshot_json text NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_conversation_id UNIQUE (conversation_id)
);
CREATE INDEX IF NOT EXISTS idx_pause_state_expires ON agentx_pause_state (expires_at);

-- 5. 技能表
CREATE TABLE IF NOT EXISTS agentx_skill (
  id bigint NOT NULL,
  name varchar(500) NOT NULL,
  skill_path varchar(3000) DEFAULT NULL,
  description varchar(3000) DEFAULT '',
  enabled smallint NOT NULL DEFAULT 1,
  file_name varchar(255) DEFAULT NULL,
  source varchar(20) DEFAULT NULL,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_agentx_skill_name ON agentx_skill (name);

-- 6. MCP 服务表
CREATE TABLE IF NOT EXISTS agentx_mcp_server (
  id bigint NOT NULL,
  name varchar(64) NOT NULL,
  transport varchar(20) NOT NULL DEFAULT 'STREAMABLE',
  url varchar(500) DEFAULT NULL,
  sse_endpoint varchar(200) DEFAULT NULL,
  command varchar(200) DEFAULT NULL,
  args varchar(2000) DEFAULT NULL,
  env varchar(2000) DEFAULT NULL,
  auth_type varchar(20) NOT NULL DEFAULT 'NONE',
  auth_token varchar(1000) DEFAULT NULL,
  timeout_ms int NOT NULL DEFAULT 60000,
  inject_mode varchar(20) NOT NULL DEFAULT 'ALWAYS',
  enabled smallint NOT NULL DEFAULT 1,
  source varchar(20) DEFAULT NULL,
  status varchar(20) NOT NULL DEFAULT 'UNKNOWN',
  last_error varchar(2000) DEFAULT NULL,
  tool_count int DEFAULT NULL,
  last_check_time timestamp DEFAULT NULL,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_agentx_mcp_server_name ON agentx_mcp_server (name);

-- 7. 文件表
CREATE TABLE IF NOT EXISTS agentx_file (
  id bigint NOT NULL,
  file_id varchar(64) NOT NULL,
  file_name varchar(255) NOT NULL,
  file_type varchar(32),
  file_size bigint,
  minio_path varchar(512),
  extracted_text text,
  status varchar(16) NOT NULL,
  embed smallint NOT NULL DEFAULT 0,
  conversation_id varchar(64),
  session_id bigint,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_file_id UNIQUE (file_id)
);
CREATE INDEX IF NOT EXISTS idx_agentx_file_session ON agentx_file (session_id);
CREATE INDEX IF NOT EXISTS idx_agentx_file_conv ON agentx_file (conversation_id);
