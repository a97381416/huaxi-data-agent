package com.llmetor.miniagentx.interrupt;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.llmetor.miniagentx.model.PauseState;
import com.llmetor.miniagentx.model.RunnableParams;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.JdbcTemplate;

import javax.sql.DataSource;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * 中断快照存储——JDBC 实现（M3）：agentx_pause_state 表，UPSERT + TTL 7 天。
 *
 * <p>替代 M1 的 {@link InMemoryPauseStateStore}（接口不变）：快照落库后进程重启不丢，
 * 恢复执行直接从表里取回。expired 行延迟清理（save 时顺手清一次，够用不做定时任务）。
 *
 * <p>序列化：PauseState 各字段手工转 Map（messagesJson 本就是字符串列表、
 * params 手工还原），不依赖 Jackson 对 Spring AI 类型的反射。
 */
public class JdbcPauseStateStore implements PauseStateStore {

    private static final Logger log = LoggerFactory.getLogger(JdbcPauseStateStore.class);

    static final String CREATE_TABLE_SQL = """
            CREATE TABLE IF NOT EXISTS agentx_pause_state (
              id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
              conversation_id varchar(100) NOT NULL,
              reason varchar(50) NOT NULL,
              safe_point varchar(50) DEFAULT NULL,
              current_round int NOT NULL,
              interrupted_at timestamp NOT NULL,
              expires_at timestamp NULL DEFAULT NULL,
              snapshot_json text NOT NULL,
              PRIMARY KEY (id),
              CONSTRAINT uk_conversation_id UNIQUE (conversation_id)
            )
            """;

    /** 默认 TTL：7 天 */
    static final long DEFAULT_TTL_MILLIS = 7L * 24 * 60 * 60 * 1000;

    private static final String UPSERT_SQL = """
            INSERT INTO agentx_pause_state
                (conversation_id, reason, safe_point, current_round, interrupted_at, expires_at, snapshot_json)
            VALUES (?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT (conversation_id) DO UPDATE SET
                reason = EXCLUDED.reason,
                safe_point = EXCLUDED.safe_point,
                current_round = EXCLUDED.current_round,
                interrupted_at = EXCLUDED.interrupted_at,
                expires_at = EXCLUDED.expires_at,
                snapshot_json = EXCLUDED.snapshot_json
            """;

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private final JdbcTemplate jdbc;
    private final long ttlMillis;

    public JdbcPauseStateStore(DataSource dataSource) {
        this(dataSource, DEFAULT_TTL_MILLIS);
    }

    public JdbcPauseStateStore(DataSource dataSource, long ttlMillis) {
        this.jdbc = new JdbcTemplate(dataSource);
        this.ttlMillis = ttlMillis;
        jdbc.execute(CREATE_TABLE_SQL);
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_pause_state_expires ON agentx_pause_state (expires_at)");
        log.info("[JdbcPauseStateStore] agentx_pause_state 表就绪");
    }

    // ==================== PauseStateStore 实现 ====================

    @Override
    public void save(PauseState state) {
        try {
            // 顺手清一次过期行（恢复频率低，不做定时任务）
            jdbc.update("DELETE FROM agentx_pause_state WHERE expires_at IS NOT NULL AND expires_at < NOW()");
            String reason = state.getReason() != null ? state.getReason().name() : "USER_INTERRUPT";
            String safePoint = state.getSafePoint() != null ? state.getSafePoint().name() : null;
            long interruptedAt = state.getInterruptedAt() > 0
                    ? state.getInterruptedAt() : System.currentTimeMillis();
            jdbc.update(UPSERT_SQL,
                    state.getConversationId(), reason, safePoint, state.getCurrentRound(),
                    new Timestamp(interruptedAt), new Timestamp(interruptedAt + ttlMillis),
                    MAPPER.writeValueAsString(toMap(state)));
            log.info("中断快照已保存(JDBC): convId={}, round={}, safePoint={}",
                    state.getConversationId(), state.getCurrentRound(), state.getSafePoint());
        } catch (Exception e) {
            log.error("中断快照保存失败: convId={}", state.getConversationId(), e);
        }
    }

    @Override
    public PauseState get(String conversationId) {
        if (conversationId == null) {
            return null;
        }
        try {
            List<String> rows = jdbc.queryForList(
                    "SELECT snapshot_json FROM agentx_pause_state WHERE conversation_id = ?",
                    String.class, conversationId);
            if (rows.isEmpty()) {
                return null;
            }
            return fromMap(MAPPER.readValue(rows.get(0), new TypeReference<Map<String, Object>>() {
            }));
        } catch (Exception e) {
            log.warn("中断快照加载失败: convId={}", conversationId, e);
            return null;
        }
    }

    @Override
    public boolean delete(String conversationId) {
        if (conversationId == null) {
            return false;
        }
        return jdbc.update("DELETE FROM agentx_pause_state WHERE conversation_id = ?", conversationId) > 0;
    }

    @Override
    public boolean has(String conversationId) {
        if (conversationId == null) {
            return false;
        }
        Boolean hit = jdbc.queryForObject(
                "SELECT COUNT(1) FROM agentx_pause_state WHERE conversation_id = ?",
                Boolean.class, conversationId);
        return Boolean.TRUE.equals(hit);
    }

    // ==================== JSON 序列化 / 反序列化 ====================
    // 包级可见：JdbcPauseStateStoreTest 直接验证 JSON 往返，不连库

    static Map<String, Object> toMap(PauseState s) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("conversationId", s.getConversationId());
        m.put("sessionId", s.getSessionId());
        m.put("query", s.getQuery());
        if (s.getParams() != null) {
            Map<String, Object> p = new LinkedHashMap<>();
            p.put("conversationId", s.getParams().getConversationId());
            p.put("userId", s.getParams().getUserId());
            p.put("customParams", s.getParams().getCustomParams());
            p.put("toolParams", s.getParams().getToolParams());
            m.put("params", p);
        }
        m.put("messagesJson", s.getMessagesJson());
        m.put("currentRound", s.getCurrentRound());
        m.put("pendingToolCalls", s.getPendingToolCalls());
        m.put("totalPromptTokens", s.getTotalPromptTokens());
        m.put("totalCompletionTokens", s.getTotalCompletionTokens());
        if (s.getReason() != null) {
            m.put("reason", s.getReason().name());
        }
        if (s.getSafePoint() != null) {
            m.put("safePoint", s.getSafePoint().name());
        }
        m.put("interruptMessage", s.getInterruptMessage());
        m.put("interruptedAt", s.getInterruptedAt());
        return m;
    }

    @SuppressWarnings("unchecked")
    static PauseState fromMap(Map<String, Object> m) {
        RunnableParams params = null;
        Object pm = m.get("params");
        if (pm instanceof Map<?, ?> p) {
            params = RunnableParams.builder()
                    .conversationId(str(p.get("conversationId")))
                    .userId(str(p.get("userId")))
                    .customParams((Map<String, String>) orEmpty(p.get("customParams")))
                    .toolParams((Map<String, Object>) orEmpty(p.get("toolParams")))
                    .build();
        }
        List<PauseState.PendingToolCall> pending = new ArrayList<>();
        if (m.get("pendingToolCalls") instanceof List<?> list) {
            for (Object o : list) {
                if (o instanceof Map<?, ?> t) {
                    pending.add(new PauseState.PendingToolCall(
                            str(t.get("id")), str(t.get("name")), str(t.get("arguments"))));
                }
            }
        }
        List<String> messagesJson = new ArrayList<>();
        if (m.get("messagesJson") instanceof List<?> list) {
            for (Object o : list) {
                if (o != null) {
                    messagesJson.add(o.toString());
                }
            }
        }
        return new PauseState(
                str(m.get("conversationId")), str(m.get("sessionId")), str(m.get("query")),
                params, messagesJson,
                num(m.get("currentRound")).intValue(),
                pending,
                num(m.get("totalPromptTokens")).longValue(),
                num(m.get("totalCompletionTokens")).longValue(),
                enumOf(PauseState.Reason.class, str(m.get("reason")), PauseState.Reason.USER_INTERRUPT),
                enumOf(PauseState.SafePoint.class, str(m.get("safePoint")), PauseState.SafePoint.INIT),
                str(m.get("interruptMessage")),
                num(m.get("interruptedAt")).longValue());
    }

    private static String str(Object v) {
        return v == null ? null : v.toString();
    }

    private static Number num(Object v) {
        return v instanceof Number n ? n : 0;
    }

    private static Object orEmpty(Object v) {
        return v instanceof Map<?, ?> map ? map : Map.of();
    }

    private static <T extends Enum<T>> T enumOf(Class<T> type, String name, T fallback) {
        if (name == null) {
            return fallback;
        }
        try {
            return Enum.valueOf(type, name);
        } catch (IllegalArgumentException e) {
            return fallback;
        }
    }
}
