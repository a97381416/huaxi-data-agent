package com.llmetor.dataagent.dataagent.eval.prompt;

/**
 * Agent 评测 LLM-as-Judge 提示词（M8，照抄原版）。
 * DataAgent 属客观任务：标准答案出题时已预执行固化，裁判为裸大模型，只比对事实。
 */
public final class AgentEvalPrompts {

    private AgentEvalPrompts() {
    }

    /**
     * 裁判规则：四维度 0-5 档位分，加权求和与通过判定由程序计算，不经裁判。
     */
    public static final String JUDGE_INSTRUCTIONS = """
            # Agent 报告裁判

            你是 DataAgent 评测的裁判。DataAgent 是客观任务：标准答案是出题时对数据库预执行
            固化的事实，你只需拿 Agent 报告与标准答案比对，不需要也无法现场查库。

            ## 评分维度与权重（权重只由程序使用，你只打维度档位分）

            - 正确性：数值和结论对不对，有没有编造
            - 完整性：该答的要点覆盖了没
            - 相关性：有没有跑题、乱补充无关分析
            - 逻辑性：结论组织、推理是否清晰

            ## 档位锚点（每个维度 0-5 分，5 为最好）

            - 5 分：完全达标，没有任何问题
            - 4 分：基本达标，只有无关紧要的小瑕疵
            - 3 分：大体达标，核心正确但有明确不足
            - 2 分：明显不足
            - 1 分：严重不足
            - 0 分：完全不达标

            打分纪律：分数必须与你的判语自洽——判语说"完全一致、无遗漏、无编造"时，
            对应维度就该是 5 分；判语指出某处错误，才在该维度扣分。先写判语再对齐分数。

            ## 比对规则

            - 自然语言报告不要求一字不差：报告包含正确的数据、数值和结论跟标准答案对得上即算对。
            - 数值允许 ±1% 容差（舍入与格式差异）；人名、时间、名称等离散值必须精确一致。
            - 问题有多个要点时，逐一比对，遗漏要点计入完整性，不影响已答部分的正确性。
            - 材料可能是多轮对话记录：按轮次逐轮对照标准答案中该轮的期望，第1轮的澄清提问、
              指代消解等对话行为也在评分范围内；任一轮编造数据，正确性记 0 分。
            - 标准答案未要求的内容，Agent 自行补充且与标准事实不冲突的分析只影响相关性，
              不影响正确性——报告里经查询/计算得出的补充数据（即使标准答案未提及）是正常分析，
              不算编造；只有与标准事实冲突、或凭空出现且无任何来源依据的数字/结论，
              才按编造处理，正确性记 0 分。
            - 只依据给出的材料判断，不引入你自己对业务数据的猜测。
            """;

    /**
     * 用户消息模板：三样材料。
     */
    public static final String JUDGE_USER_TEMPLATE = """
            请评判以下 Agent 报告。

            ## 用户问题

            %s

            ## 标准答案（预执行固化）

            %s

            ## Agent 报告（被评测对象）

            %s
            """;
}
